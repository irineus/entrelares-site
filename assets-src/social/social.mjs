// L-45 — pure renderers for the social kit: the slides' HTML and the owner's calendar.
//
// Nothing here touches the disk or a browser, so test/social.test.js can call both and compare
// them with what is committed (the L-50 build.test.js shape). build.mjs is the CLI that writes the
// files and drives headless Chrome.
//
// One slide = one <section id="<post id>-<n>"> of 1080x1350 (Instagram's 4:5 portrait), shown
// alone through :target, so a screenshot of carrosseis.html#c01-3 is slide 3 of c01. The page
// opened as #check lays every slide out at once and reports the ones whose text does not fit.

const esc = (s) => String(s)
  .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

const WEEKDAYS = ["domingo", "segunda", "terça", "quarta", "quinta", "sexta", "sábado"];

/** Weekday of an ISO date, read as a calendar date (no timezone can move it). */
export function weekday(iso) {
  const [y, m, d] = iso.split("-").map(Number);
  return WEEKDAYS[new Date(Date.UTC(y, m - 1, d)).getUTCDay()];
}

/** File name of one slide's PNG, relative to assets-src/social/. */
export const slideFile = (post, i) => `dezembro-2026/${post.date}-${post.slug}-${i + 1}.png`;

export const carousels = (posts) => posts.filter((p) => p.kind === "carousel");

/** The caption exactly as the owner pastes it: paragraphs, then the hashtags on their own line. */
export const captionText = (post) => [...post.caption, post.hashtags.join(" ")].join("\n\n");

/** Two-house strip drawn on every cover: a 2-2-3 fortnight, the same pattern the home paints. */
function strip() {
  const a = "a", b = "b";
  const days = [a, a, b, b, a, a, a, b, b, a, a, b, b, b];
  return `<div class="strip" aria-hidden="true">${days.map((h) => `<i class="d ${h}"></i>`).join("")}</div>`;
}

function slideBody(s, cta, brandLine) {
  const num = s.n ? `<span class="num n${s.n % 2 ? "a" : "b"}">${s.n}</span>` : "";
  switch (s.type) {
    case "cover":
      return `<p class="kicker">${esc(s.kicker)}</p><h1>${esc(s.title)}</h1><p class="lead">${esc(s.body)}</p>${strip()}<p class="swipe">Arraste para o lado &rarr;</p>`;
    case "text":
      return `${num}<h2>${esc(s.title)}</h2><p class="body">${esc(s.body)}</p>`
        + (s.pro ? `<p class="pc pro"><b>A favor</b>${esc(s.pro)}</p>` : "")
        + (s.con ? `<p class="pc con"><b>Contra</b>${esc(s.con)}</p>` : "")
        + (s.note ? `<p class="note">${esc(s.note)}</p>` : "");
    case "quote":
      return `${num}<h2>${esc(s.title)}</h2><blockquote>${esc(s.quote)}</blockquote>`
        + (s.body ? `<p class="body">${esc(s.body)}</p>` : "");
    case "list":
      return `<h2>${esc(s.title)}</h2><ul>${s.items.map((it, k) => `<li class="${k % 2 ? "b" : "a"}">${esc(it)}</li>`).join("")}</ul>`;
    case "cta": {
      const c = cta[s.cta];
      return `<h2>${esc(s.title)}</h2><p class="line">${esc(c.line)}</p><p class="action">${esc(c.action)}</p><p class="brandline">${esc(brandLine)}</p>`;
    }
    default:
      throw new Error(`unknown slide type ${s.type}`);
  }
}

